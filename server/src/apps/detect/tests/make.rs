const MAKEFILE: &str = "# Project tasks
BIN := bin/app
GOFLAGS ?= -trimpath
VERSION = $(shell git describe)

.PHONY: all build test lint fmt run dev clean \\
        docker-build db.migrate _internal

all: build

build: ## Build the binary
\tgo build -o $(BIN) ./cmd/app

test:
\tgo test ./...

lint fmt:
\tgolangci-lint run

run: build
\t./$(BIN) --port 8088

dev:
\tair

clean:
\trm -rf bin/

docker-build:
\tdocker build -t app .

db.migrate:
\tmigrate -path db -database $$DATABASE_URL up

deploy: build
\trsync -av bin/ prod:/opt/app/
\tssh prod systemctl restart app

publish:
\tdocker push registry.example.com/app:latest

_internal:
\techo private

%.o: %.c
\t$(CC) -c $<

$(BIN): main.go
\tgo build -o $@

bin/tool: tool.go
\tgo build -o $@

main.o: main.c
\tcc -c main.c

install:
\tcp $(BIN) /usr/local/bin
";

#[test]
fn makefile_targets() {
    let t = make_targets(MAKEFILE);
    let got: Vec<&str> = t.iter().map(|e| e.name.as_str()).collect();
    assert_eq!(
        got,
        vec!["all", "build", "test", "lint", "fmt", "run", "dev", "clean", "docker-build", "db.migrate", "deploy", "publish", "install"],
        "phony + conventional names; no patterns, variables, paths, files or private targets"
    );
    let run_body = &t.iter().find(|e| e.name == "run").unwrap().body;
    assert!(run_body.contains("--port 8088"), "{run_body}");
    assert!(make_targets("# CMAKE generated file: DO NOT EDIT!\nall: cmake_check_build_system\n").is_empty());
    assert!(make_targets("# Makefile.in generated by automake 1.16.5 from Makefile.am.\nall: x\n").is_empty());
}

#[test]
fn makefile_runs() {
    let d = tree(&[("Makefile", MAKEFILE), ("docs/Makefile", ".PHONY: help html\nhelp:\n\t@sphinx-build -M help . _build\nhtml:\n\tsphinx-build -b html . _build\n")]);
    let pf = detect_checked(d.path());
    let r = run(&pf, "make run");
    assert_eq!((r.kind, r.command.as_str(), r.port), (RunKind::Server, "make run", Some(8088)));
    assert_eq!(r.source.as_deref(), Some("detected:Makefile#run"));
    assert_eq!(run(&pf, "make dev").kind, RunKind::Server);
    assert_eq!(run(&pf, "make test").kind, RunKind::Test);
    assert_eq!(run(&pf, "make build").kind, RunKind::Build);
    assert_eq!(run(&pf, "make all").kind, RunKind::Build);
    assert_eq!(run(&pf, "make lint").kind, RunKind::Task);
    assert_eq!(run(&pf, "make clean").group.as_deref(), Some("tasks"));
    // A recipe that reaches another machine or publishes is a deploy, whatever its name.
    assert_eq!(run(&pf, "make deploy").group.as_deref(), Some("deploy"));
    assert_eq!(run(&pf, "make publish").group.as_deref(), Some("deploy"));
    assert!(crate::apps::runs::needs_confirmation(run(&pf, "make publish")));
    assert_eq!(run(&pf, "make html (docs)").cwd, "docs");
}

const JUSTFILE: &str = r#"set dotenv-load
set shell := ["bash", "-cu"]

alias b := build
export RUST_LOG := "info"
version := `git describe --tags`

# Show the recipes
default:
    @just --list

# Build everything
build *args:
    cargo build {{args}}

[group('dev')]
serve port="8000":
    python -m http.server {{port}}

test filter="": build
    cargo test {{filter}}

deploy env:
    ./scripts/deploy.sh {{env}}

[private]
helper:
    echo hidden

_hidden:
    echo hidden

[windows]
win-only:
    echo windows

[linux]
linux-only:
    echo linux

files +paths:
    ls {{paths}}

ship:
    rsync -av dist/ web:/var/www/
"#;

#[test]
fn justfile_recipes() {
    let r = just_recipes(JUSTFILE);
    let got: Vec<&str> = r.iter().map(|e| e.name.as_str()).collect();
    assert_eq!(got, vec!["default", "build", "serve", "test", "linux-only", "ship"]);
    assert!(needs_args("env") && needs_args("+paths") && needs_args("$name"));
    assert!(!needs_args("*args") && !needs_args("port=\"8000\"") && !needs_args("filter=\"a b\"") && !needs_args(""));
    let d = tree(&[("justfile", JUSTFILE)]);
    let pf = detect_checked(d.path());
    let s = run(&pf, "just serve");
    assert_eq!((s.kind, s.command.as_str()), (RunKind::Server, "just serve"));
    assert_eq!(run(&pf, "just test").kind, RunKind::Test);
    assert_eq!(run(&pf, "just ship").group.as_deref(), Some("deploy"));
    assert!(!has_run(&pf, "just deploy") && !has_run(&pf, "just helper"), "{:?}", names(&pf));
}

