#[test]
fn procfiles() {
    let d = tree(&[
        ("Procfile", "web: gunicorn app:app --bind 0.0.0.0:$PORT\nworker: celery -A app worker\nrelease: python manage.py migrate\n# comment\n"),
        ("Procfile.dev", "web: bin/rails server -p ${PORT:-3000}\ncss: bin/rails tailwindcss:watch\n"),
    ]);
    let pf = detect_checked(d.path());
    let web = run(&pf, "Procfile: web");
    assert_eq!((web.kind, web.port, web.command.as_str()), (RunKind::Server, Some(5000), "gunicorn app:app --bind 0.0.0.0:$PORT"));
    assert_eq!(web.env.get("PORT").map(String::as_str), Some("5000"));
    assert_eq!(run(&pf, "Procfile: worker").kind, RunKind::Task);
    assert!(!has_run(&pf, "Procfile: release"), "the release phase runs on deploy");
    let dev = run(&pf, "Procfile.dev: web");
    assert_eq!((dev.port, dev.env.get("PORT").map(String::as_str)), (Some(3000), Some("3000")));
    assert_eq!(run(&pf, "Procfile.dev: css").port, None);

    // Rails 7: `web: bin/rails server` repeats `rails server`; a web process that
    // ignores $PORT has no port to claim; Python's http.server listens on 8000.
    let d = tree(&[
        ("Gemfile", "gem \"rails\"\n"),
        ("config/application.rb", "module App; end\n"),
        ("bin/rails", ""),
        ("Procfile.dev", "web: bin/rails server\njs: yarn build --watch\n"),
        ("worker/Procfile", "web: ./bin/serve-forever\n"),
        ("static/Procfile", "web: python -m http.server\n"),
    ]);
    let pf = detect_checked(d.path());
    assert!(!has_run(&pf, "Procfile.dev: web"), "{:?}", names(&pf));
    assert_eq!(run(&pf, "rails server").port, Some(3000));
    assert_eq!(run(&pf, "Procfile.dev: js").kind, RunKind::Task);
    let w = run(&pf, "Procfile: web (worker)");
    assert_eq!((w.kind, w.port, w.env.is_empty()), (RunKind::Server, None, true));
    let s = run(&pf, "Procfile: web (static)");
    assert_eq!((s.kind, s.port, s.preview.as_deref()), (RunKind::Server, Some(8000), Some("http://localhost:8000/")));
}

/// Rails 7 with `bin/dev`: `Procfile.dev`'s `web: bin/rails server -p 3000` is the
/// `rails server` run again (same program, same port), not a third server on :3000.
#[test]
fn rails_procfile_dev_web_is_not_a_third_server() {
    let d = tree(&[
        ("Gemfile", "gem \"rails\"\n"),
        ("config/application.rb", "module App; end\n"),
        ("bin/rails", ""),
        ("bin/dev", "#!/usr/bin/env sh\nexec foreman start -f Procfile.dev\n"),
        ("Procfile.dev", "web: bin/rails server -p 3000\ncss: bin/rails tailwindcss:watch\n"),
        ("api/Procfile", "web: bundle exec puma -p 9000\n"),
    ]);
    let pf = detect_checked(d.path());
    let servers: Vec<&str> = pf.runs.iter().filter(|r| r.port == Some(3000)).map(|r| r.name.as_str()).collect();
    assert_eq!(servers, vec!["bin/dev", "rails server"], "{:?}", names(&pf));
    assert!(has_run(&pf, "Procfile.dev: css"), "{:?}", names(&pf));
    assert_eq!(run(&pf, "Procfile: web (api)").port, Some(9000), "another directory, another server");
}

/// `python -m http.server [port]`: a server with a port, a ready line and a preview.
#[test]
fn python_http_server_has_a_port_and_a_ready_line() {
    use super::super::port_in;
    assert_eq!(port_in("python3 -m http.server 8123 --bind 127.0.0.1"), Some(8123));
    assert_eq!(port_in("python -m http.server"), Some(8000));
    assert_eq!(port_in("python3 -m http.server -b 0.0.0.0 -d site 9001"), Some(9001));
    assert_eq!(port_in("python3 -m http.server --directory site"), Some(8000));
    assert_eq!(port_in("python3 -m http.server $PORT"), None, "the $PORT convention decides");
    assert_eq!(port_in("python3 -m http.server --bind 0.0.0.0:7000"), Some(7000));
    let d = tree(&[
        ("Procfile", "web: python3 -m http.server 8123 --bind 127.0.0.1\n"),
        ("Makefile", ".PHONY: serve docs\nserve:\n\tcd site && python3 -m http.server 8765\ndocs:\n\tpython3 -m http.server\n"),
    ]);
    let pf = detect_checked(d.path());
    let web = run(&pf, "Procfile: web");
    assert_eq!((web.kind, web.port, web.preview.as_deref()), (RunKind::Server, Some(8123), Some("http://localhost:8123/")));
    let ready = regex::Regex::new(web.ready.as_ref().and_then(|r| r.log.as_deref()).unwrap()).unwrap();
    let line = "Serving HTTP on 127.0.0.1 port 8123 (http://127.0.0.1:8123/) ...";
    assert_eq!(ready.captures(line).unwrap().get(1).map(|m| m.as_str()), Some("http://127.0.0.1:8123/"));
    let serve = run(&pf, "make serve");
    assert_eq!((serve.kind, serve.port, serve.ready.is_some()), (RunKind::Server, Some(8765), true));
    assert_eq!((run(&pf, "make docs").port, run(&pf, "make docs").ready.is_none()), (None, true), "a task is not a server");
}

/// A dependency-only recipe that only names another offered one (`default: up`)
/// is not offered twice; an aggregate of several is kept.
#[test]
fn just_aliases_are_not_offered_twice() {
    let src = "default: up\nup:\n    docker compose up -d\nci: lint test\nlint:\n    ruff check .\ntest:\n    pytest\nhidden: _setup\n_setup:\n    ./setup.sh\n";
    let got: Vec<String> = just_recipes(src).into_iter().map(|e| e.name).collect();
    assert_eq!(got, vec!["up", "ci", "lint", "test", "hidden"]);
}

#[test]
fn same_name_in_one_directory_is_qualified_by_tool() {
    // A Python console script `serve` next to an npm script `serve`.
    let d = tree(&[
        ("package.json", r#"{"scripts":{"serve":"vite preview"}}"#),
        ("pyproject.toml", "[project]\nname = \"x\"\n[project.scripts]\nserve = \"x.cli:serve\"\n"),
    ]);
    let pf = detect_checked(d.path());
    assert_eq!(run(&pf, "serve").command, "npm run serve");
    assert_eq!(run(&pf, "serve · pyproject").command, "serve");
}
